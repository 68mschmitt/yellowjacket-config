#!/usr/bin/env python3
"""Export the approved browser props as deduplicated 24px LVGL I4 tiles.

Requires Chromium and Pillow only for regeneration, not firmware builds.
"""
import base64
import io
import json
from html.parser import HTMLParser
from pathlib import Path
import subprocess

from PIL import Image

ROOT = Path(__file__).resolve().parents[1]


class ExportParser(HTMLParser):
    active = False
    result = ""

    def handle_starttag(self, tag, attrs):
        if tag == "pre" and ("id", "exported-frames") in attrs:
            self.active = True

    def handle_endtag(self, tag):
        if tag == "pre":
            self.active = False

    def handle_data(self, data):
        if self.active:
            self.result += data


def main():
    html = subprocess.check_output([
        "chromium", "--headless", "--no-sandbox", "--disable-gpu",
        "--virtual-time-budget=3000", "--dump-dom",
        (ROOT / "previews/cat-layers/index.html").as_uri() + "?export",
    ], text=True)
    parser = ExportParser()
    parser.feed(html)
    frames = json.loads(parser.result)
    tiles, indexes, scenes = [], {}, []
    for name, images in frames.items():
        variants = []
        for data in images:
            image = Image.open(io.BytesIO(base64.b64decode(data.split(",")[1]))).convert("RGBA")
            entries = []
            for y in range(72, 192, 24):
                for x in range(24, 240, 24):
                    tile = image.crop((x, y, x + 24, y + 24))
                    bounds = tile.getbbox()
                    if not bounds:
                        continue
                    x0, y0, x1, y1 = bounds
                    # I4 stores two pixels per byte; trim transparent borders
                    # and round the crop width up to an even number.
                    width = (x1 - x0 + 1) & ~1
                    height = y1 - y0
                    tile = tile.crop((x0, y0, x0 + width, y1))
                    indexed = tile.quantize(colors=16, method=Image.Quantize.FASTOCTREE)
                    palette = indexed.getpalette("RGBA")
                    palette = (palette + [0] * 64)[:64]
                    raw = bytearray()
                    for i in range(0, 64, 4):
                        r, g, b, a = palette[i:i + 4]
                        raw.extend((b, g, r, a))
                    pixels = list(indexed.getdata())
                    raw.extend((pixels[i] << 4) | pixels[i + 1] for i in range(0, len(pixels), 2))
                    key = (bytes(raw), width, height)
                    if key not in indexes:
                        indexes[key] = len(tiles)
                        tiles.append(key)
                    entries.append((indexes[key], x + x0, y + y0))
            variants.append(entries)
            assert len(entries) <= 24, f"{name} exceeds the renderer's tile pool"
        scenes.append((name, variants))
    out = ['/* Generated by scripts/convert-cat-overlays.py. */', '#include "cat_overlays.h"']
    for i, (data, width, height) in enumerate(tiles):
        out.append(f"static const uint8_t data_{i}[] __attribute__((aligned(4))) = {{")
        for start in range(0, len(data), 24):
            out.append("  " + ", ".join(f"0x{v:02x}" for v in data[start:start + 24]) + ",")
        out.append("};")
    out.append("const lv_image_dsc_t cat_overlay_tiles[] = {")
    for i, (data, width, height) in enumerate(tiles):
        out.append("  { .header = { .magic = LV_IMAGE_HEADER_MAGIC, .cf = LV_COLOR_FORMAT_I4,"
                   f" .w = {width}, .h = {height}, .stride = {width // 2} }}, .data_size = sizeof(data_{i}), .data = data_{i} }},")
    out.append("};")
    for scene, (name, variants) in enumerate(scenes):
        for phase, entries in enumerate(variants):
            if entries:
                out.append(f"static const struct cat_overlay_tile scene_{scene}_{phase}[] = {{")
                out.extend(f"  {{ {i}, {x}, {y} }}," for i, x, y in entries)
                out.append("};")
    out.append("const struct cat_overlay_frame cat_overlay_frames[13][2] = {")
    for scene, (name, variants) in enumerate(scenes):
        out.append(f"  /* {name} */ {{")
        for phase, entries in enumerate(variants):
            out.append(f"    {{ {len(entries)}, " + (f"scene_{scene}_{phase}" if entries else "NULL") + " },")
        out.append("  },")
    out.append("};")
    (ROOT / "src/display/cat_overlays.c").write_text("\n".join(out) + "\n")
    print(f"{len(tiles)} tiles, {sum(len(t[0]) for t in tiles)} image bytes; max frame {max(len(v) for _, vs in scenes for v in vs)} tiles")


if __name__ == "__main__":
    main()
